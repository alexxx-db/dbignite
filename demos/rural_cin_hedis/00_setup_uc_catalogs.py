# DBTITLE 1,Wait for Pipeline and Query Quarantine
import time

for attempt in range(30):
    state = w.pipelines.get(pipeline_id).state.value
    if state in ("IDLE", "FAILED"):
        break
    print(f"Pipeline state: {state} (waiting...)")
    time.sleep(10)

print(f"Pipeline final state: {state}")

if state == "IDLE":
    print("\n--- Quarantine table (records rejected by quality rules) ---")
    display(spark.sql(f"SELECT * FROM `{catalog}`.`bronze`.`quarantine_adt`"))
else:
    print(f"Pipeline did not complete successfully. Check pipeline UI for details.")

