# MAGIC ## 4. Create DLT Pipeline for Bronze Ingest
# MAGIC
# MAGIC The pipeline runs on **DLT Serverless** in **Triggered** mode — it processes new files
# MAGIC when triggered, then shuts down. No idle compute, no grant dollars spent on waiting.

# COMMAND ----------

# DBTITLE 1,Create Bronze ADT Pipeline
from databricks.sdk import WorkspaceClient
from databricks.sdk.service.pipelines import (
    PipelineCluster,
    PipelineLibrary,
    NotebookLibrary,
)

w = WorkspaceClient()

# Resolve the notebook path relative to this notebook
nb_context = json.loads(
    dbutils.notebook.entry_point.getDbutils().notebook().getContext().toJson()
)
notebook_dir = "/".join(nb_context["extraContext"]["notebook_path"].split("/")[:-1])
bronze_notebook = f"{notebook_dir}/01_bronze_ingest_adt"

pipeline_name = f"{catalog}_bronze_adt"

# Check if pipeline already exists
existing_pipelines = [
    p for p in w.pipelines.list_pipelines()
    if p.name == pipeline_name
]

if existing_pipelines:
    pipeline_id = existing_pipelines[0].pipeline_id
    print(f"Pipeline '{pipeline_name}' already exists: {pipeline_id}")
else:
    result = w.pipelines.create(
        name=pipeline_name,
        catalog=catalog,
        target="bronze",
        serverless=True,
        continuous=False,  # Triggered, not continuous — zero idle cost
        libraries=[
            PipelineLibrary(
                notebook=NotebookLibrary(path=bronze_notebook)
            )
        ],
        configuration={
            "raw_feeds_volume": f"/Volumes/{catalog}/bronze/raw_feeds/adt_records/",
        },
    )
    pipeline_id = result.pipeline_id
    print(f"Created pipeline '{pipeline_name}': {pipeline_id}")

# COMMAND ----------

# DBTITLE 1,Trigger Pipeline Run
update = w.pipelines.start_update(pipeline_id=pipeline_id, full_refresh=True)
print(f"Pipeline triggered. Update ID: {update.update_id}")
print(f"Monitor at: #joblist/pipelines/{pipeline_id}")
print("While it runs, open notebook 01_bronze_ingest_adt to walk through the pipeline code.")

